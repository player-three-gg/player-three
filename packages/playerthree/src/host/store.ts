/**
 * Built-in storage: in-memory stores (the default) and JSON-file stores for commander rosters (`dataDir`), the
 * published-policy pool (`poolDir`) and the session history (`history.dir`). Games with their own database implement
 * the store interfaces instead (or use `playerthree/postgres`).
 */
import { appendFileSync, existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { compareLogEntries, type CommanderLogHead, type CommanderLogStore, type CommanderLogVerdictRow, type StoredCommanderLogEntry } from '../commander-log.ts';
import { readFile, rename, rm, writeFile } from 'node:fs/promises';
import { POLICY_RUNTIMES } from '../manifest.ts';
import type { CommanderStore, CommanderStoreData, HistoryStore, PoolStore, Replay, SessionRecord, StoredCommanderArtifact, StoredOwner, StoredPolicyArtifact, StoredPoolEntry } from './types.ts';

/** Owner ids the registry accepts (also safe as file names). */
export const OWNER_RE = /^[A-Za-z0-9_-]{8,64}$/;
/** Commander ids are opaque UUIDs generated by the registry. */
const COMMANDER_ID = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;
/** Pool entry ids (also safe as file names). */
export const POOL_ID = /^pol_[0-9]{1,9}$/;
/** Session ids the JSON history store accepts as file names. */
const SESSION_ID = /^[A-Za-z0-9_-]{1,64}$/;

/** Provenance of a deployed (not imported) library version. */
export const DEPLOYED: StoredCommanderArtifact['provenance'] = Object.freeze({ parent: null, license: null, author: null });

/** A stored commander artifact; members an older record lacks (source, detail, provenance) load as null. */
export function commanderArtifact(raw: StoredPolicyArtifact & Partial<Pick<StoredCommanderArtifact, 'source' | 'detail' | 'provenance'>>): StoredCommanderArtifact {
  return { ...raw, source: raw.source ?? null, detail: raw.detail ?? null, provenance: raw.provenance ?? { ...DEPLOYED } };
}

/** In-memory commander roster store (the default without `dataDir` or `commanderStore`): lost on restart. */
export function memoryCommanderStore(): CommanderStore {
  let key: string | null = null;
  const owners = new Map<string, StoredOwner>();
  const artifacts = new Map<string, StoredCommanderArtifact>();
  const akey = (owner: string, commanderId: string, version: number) => `${owner}\0${commanderId}\0${version}`;
  return {
    load: () => ({ key, owners: [...owners.values()].map((o) => structuredClone(o)) }),
    saveKey(k) {
      key = k;
    },
    saveOwner(record) {
      owners.set(record.owner, structuredClone(record));
    },
    deleteOwner(owner) {
      owners.delete(owner);
      for (const k of [...artifacts.keys()]) if (k.startsWith(`${owner}\0`)) artifacts.delete(k);
    },
    saveArtifact(owner, commanderId, version, artifact) {
      artifacts.set(akey(owner, commanderId, version), structuredClone(artifact));
    },
    loadArtifact(owner, commanderId, version) {
      const a = artifacts.get(akey(owner, commanderId, version));
      return a ? structuredClone(a) : undefined;
    },
    deleteArtifact(owner, commanderId, version) {
      artifacts.delete(akey(owner, commanderId, version));
    },
  };
}

/**
 * JSON-file store: `<dir>/commanders.json` (key + rosters, written atomically) and one file per library version
 * under `<dir>/artifacts/<owner>/<commander-id>/<version>.json` (runtime, code, hashes, source, detail, provenance).
 * Owner and commander ids are pattern-checked before they become path components.
 * `commanders.json` holds the host key every commander token is derived from, and artifacts are owners' private
 * policy code: directories are created 0700 and files written 0600 so other local users cannot read either.
 */
export function jsonCommanderStore(dir: string): CommanderStore {
  const index = join(dir, 'commanders.json');
  const data: CommanderStoreData = { key: null, owners: [] };
  const owners = new Map<string, StoredOwner>();
  const safe = (owner: string, commanderId: string): void => {
    if (!OWNER_RE.test(owner) || !COMMANDER_ID.test(commanderId)) throw new Error('playerthree/commanders: unsafe owner or commander id');
  };
  const base = (owner: string, commanderId: string, version: number) => {
    safe(owner, commanderId);
    if (!Number.isSafeInteger(version) || version < 1) throw new Error('playerthree/commanders: bad version');
    return join(dir, 'artifacts', owner, commanderId, String(version));
  };
  const flush = (): void => {
    const tmp = `${index}.${process.pid}.tmp`;
    writeFileSync(tmp, JSON.stringify({ version: 1, key: data.key, owners: [...owners.values()] }), { mode: 0o600 });
    renameSync(tmp, index);
  };
  return {
    load() {
      mkdirSync(dir, { recursive: true, mode: 0o700 });
      if (!existsSync(index)) return { key: null, owners: [] };
      const raw = JSON.parse(readFileSync(index, 'utf8')) as { key?: unknown; owners?: unknown };
      if (!Array.isArray(raw.owners)) throw new Error('playerthree/commanders: malformed commanders.json');
      data.key = typeof raw.key === 'string' ? raw.key : null;
      for (const o of raw.owners as StoredOwner[]) {
        if (typeof o?.owner !== 'string' || !OWNER_RE.test(o.owner)) throw new Error('playerthree/commanders: malformed owner in commanders.json');
        owners.set(o.owner, o);
      }
      return { key: data.key, owners: [...owners.values()].map((o) => structuredClone(o)) };
    },
    saveKey(k) {
      data.key = k;
      flush();
    },
    saveOwner(record) {
      if (!OWNER_RE.test(record.owner)) throw new Error('playerthree/commanders: unsafe owner');
      owners.set(record.owner, structuredClone(record));
      flush();
    },
    deleteOwner(owner) {
      if (!OWNER_RE.test(owner)) throw new Error('playerthree/commanders: unsafe owner');
      owners.delete(owner);
      flush();
      rmSync(join(dir, 'artifacts', owner), { recursive: true, force: true });
    },
    saveArtifact(owner, commanderId, version, artifact) {
      const file = `${base(owner, commanderId, version)}.json`;
      mkdirSync(join(dir, 'artifacts', owner, commanderId), { recursive: true, mode: 0o700 });
      writeFileSync(file, JSON.stringify(artifact), { mode: 0o600 });
    },
    loadArtifact(owner, commanderId, version) {
      const file = `${base(owner, commanderId, version)}.json`;
      return existsSync(file) ? commanderArtifact(JSON.parse(readFileSync(file, 'utf8')) as StoredPolicyArtifact) : undefined;
    },
    deleteArtifact(owner, commanderId, version) {
      rmSync(`${base(owner, commanderId, version)}.json`, { force: true });
    },
  };
}

// ------------------------------------------------------------------ pool

/** In-memory policy pool store (the default without `poolDir` or `poolStore`): lost on restart. */
export function memoryPoolStore(): PoolStore {
  const entries = new Map<string, StoredPoolEntry>();
  const artifacts = new Map<string, StoredPolicyArtifact>();
  return {
    load: () => ({ entries: [...entries.values()].map((e) => ({ ...e })) }),
    saveEntry(entry) {
      entries.set(entry.id, { ...entry });
    },
    deleteEntry(id) {
      entries.delete(id);
      artifacts.delete(id);
    },
    saveArtifact(id, artifact) {
      artifacts.set(id, { ...artifact });
    },
    loadArtifact(id) {
      const a = artifacts.get(id);
      return a ? { ...a } : undefined;
    },
  };
}

/**
 * JSON-file pool store: `<dir>/pool.json` (`{version:1, entries}`, written atomically) and one artifact file per entry,
 * `<dir>/<id>.json` (runtime, code and surface hash). Every write re-reads `pool.json`, so entries of other games sharing the directory are kept.
 * Entry ids are pattern-checked before they become file names.
 */
export function jsonPoolStore(dir: string): PoolStore {
  const index = join(dir, 'pool.json');
  const safe = (id: string): string => {
    if (!POOL_ID.test(id)) throw new Error('playerthree/pool: unsafe entry id');
    return join(dir, id);
  };
  const read = (): StoredPoolEntry[] => {
    if (!existsSync(index)) return [];
    const data = JSON.parse(readFileSync(index, 'utf8')) as { entries?: unknown };
    if (!Array.isArray(data.entries)) throw new Error('playerthree/pool: malformed pool.json');
    return data.entries as StoredPoolEntry[];
  };
  const flush = (entries: StoredPoolEntry[]): void => {
    const tmp = `${index}.${process.pid}.tmp`;
    writeFileSync(tmp, JSON.stringify({ version: 1, entries }, null, 1));
    renameSync(tmp, index);
  };
  return {
    load() {
      mkdirSync(dir, { recursive: true });
      const entries = read();
      for (const e of entries) {
        // Ids become file names: refuse anything that is not exactly `pol_<digits>`.
        if (typeof e?.id !== 'string' || !POOL_ID.test(e.id)) throw new Error('playerthree/pool: malformed entry id in pool.json');
        if (!(POLICY_RUNTIMES as readonly string[]).includes(e.runtime)) throw new Error('playerthree/pool: malformed entry runtime in pool.json');
      }
      return { entries };
    },
    saveEntry(entry) {
      safe(entry.id);
      const entries = read();
      const i = entries.findIndex((e) => e.id === entry.id);
      if (i === -1) entries.push(entry);
      else entries[i] = entry;
      flush(entries);
    },
    deleteEntry(id) {
      const base = safe(id);
      flush(read().filter((e) => e.id !== id));
      rmSync(`${base}.json`, { force: true });
    },
    saveArtifact(id, artifact) {
      writeFileSync(`${safe(id)}.json`, JSON.stringify(artifact));
    },
    loadArtifact(id) {
      const file = `${safe(id)}.json`;
      return existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) as StoredPolicyArtifact : undefined;
    },
  };
}


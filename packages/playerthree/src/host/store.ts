/** Entries and verdict rows held in memory: the shared state behind both built-in log stores. */
class LogState {
  readonly rows: StoredCommanderLogEntry[];
  readonly verdicts: CommanderLogVerdictRow[];
  private readonly byCommander = new Map<string, StoredCommanderLogEntry[]>();

  constructor(rows: StoredCommanderLogEntry[] = [], verdicts: CommanderLogVerdictRow[] = []) {
    this.rows = rows;
    this.verdicts = verdicts;
    for (const row of rows) this.list(row.commanderId).push(row);
  }

  private list(commanderId: string): StoredCommanderLogEntry[] {
    let list = this.byCommander.get(commanderId);
    if (!list) this.byCommander.set(commanderId, (list = []));
    return list;
  }

  heads(): CommanderLogHead[] {
    return [...this.byCommander].map(([commanderId, list]) => {
      const last = list.at(-1)!.entry;
      const decided = list.filter((r) => !r.entry.selfPlay && r.entry.outcome !== 'unknown');
      return {
        commanderId, seq: last.seq, digest: last.digest,
        wins: decided.filter((r) => r.entry.outcome === 'win').length,
        losses: decided.filter((r) => r.entry.outcome === 'loss').length,
        draws: decided.filter((r) => r.entry.outcome === 'draw').length,
      };
    });
  }

  add(row: StoredCommanderLogEntry): void {
    const list = this.list(row.commanderId);
    // Insert only: (commander, seq) and (match, commander) are unique.
    if (list.some((r) => r.entry.seq === row.entry.seq || r.entry.matchId === row.entry.matchId)) throw new Error('playerthree/commander-log: duplicate entry');
    list.push(row);
    this.rows.push(row);
  }

  entries(commanderId: string, afterSeq = 0): StoredCommanderLogEntry[] {
    return (this.byCommander.get(commanderId) ?? []).filter((r) => r.entry.seq > afterSeq).map((r) => structuredClone(r));
  }

  match(matchId: string): StoredCommanderLogEntry[] {
    return this.rows.filter((r) => r.entry.matchId === matchId).map((r) => structuredClone(r));
  }

  all(): StoredCommanderLogEntry[] {
    return this.rows.map((r) => structuredClone(r)).sort((a, b) => compareLogEntries(a.entry, b.entry));
  }

  /** Drops the commander's sealed parts; true when anything changed. */
  redact(commanderId: string): boolean {
    let changed = false;
    for (const row of this.byCommander.get(commanderId) ?? []) if (row.sealed !== null) { row.sealed = null; changed = true; }
    return changed;
  }
}

/** In-memory commander log store (the default without `dataDir` or `commanderLog.store`): lost on restart. */
export function memoryCommanderLogStore(): CommanderLogStore {
  const state = new LogState();
  return {
    heads: () => state.heads(),
    append: (row) => state.add(structuredClone(row)),
    entries: (commanderId, afterSeq) => state.entries(commanderId, afterSeq),
    match: (matchId) => state.match(matchId),
    all: () => state.all(),
    appendVerdict: (row) => { state.verdicts.push(structuredClone(row)); },
    verdicts: () => structuredClone(state.verdicts),
    redact: (commanderId) => { state.redact(commanderId); },
  };
}

/**
 * JSONL log store: one line per entry (`{"entry":…}`) or verdict row (`{"verdict":…}`), appended (0600). A privacy
 * tombstone rewrites the file atomically without the commander's sealed parts (the only rewrite). Use one file per game.
 */
export function jsonlCommanderLogStore(file: string): CommanderLogStore {
  let state: LogState | undefined;
  const loaded = (): LogState => {
    if (state) return state;
    mkdirSync(dirname(file), { recursive: true, mode: 0o700 });
    const rows: StoredCommanderLogEntry[] = [];
    const verdicts: CommanderLogVerdictRow[] = [];
    if (existsSync(file)) {
      for (const line of readFileSync(file, 'utf8').split('\n')) {
        if (!line) continue;
        const parsed = JSON.parse(line) as { entry?: StoredCommanderLogEntry; verdict?: CommanderLogVerdictRow };
        if (parsed.entry) rows.push(parsed.entry);
        else if (parsed.verdict) verdicts.push(parsed.verdict);
        else throw new Error('playerthree/commander-log: malformed log line');
      }
    }
    state = new LogState(rows, verdicts);
    return state;
  };
  const line = (value: unknown): void => appendFileSync(file, `${JSON.stringify(value)}\n`, { mode: 0o600 });
  return {
    heads: () => loaded().heads(),
    append(row) {
      loaded().add(structuredClone(row));
      line({ entry: row });
    },
    entries: (commanderId, afterSeq) => loaded().entries(commanderId, afterSeq),
    match: (matchId) => loaded().match(matchId),
    all: () => loaded().all(),
    appendVerdict(row) {
      loaded().verdicts.push(structuredClone(row));
      line({ verdict: row });
    },
    verdicts: () => structuredClone(loaded().verdicts),
    redact(commanderId) {
      const s = loaded();
      if (!s.redact(commanderId)) return;
      const tmp = `${file}.${process.pid}.tmp`;
      writeFileSync(tmp, [...s.rows.map((entry) => JSON.stringify({ entry })), ...s.verdicts.map((verdict) => JSON.stringify({ verdict }))].map((l) => `${l}\n`).join(''), { mode: 0o600 });
      renameSync(tmp, file);
    },
  };
}

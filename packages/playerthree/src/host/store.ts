/**
 * JSON-file history store: one `<dir>/<session>.json` per session
 * (`{format:"playerthree.session", version:1, record, replay}`), written atomically (temp file + rename). Loading
 * removes temp files left by an interrupted write and skips unreadable files. Use one directory per game.
 */
export function jsonHistoryStore(dir: string): HistoryStore {
  const file = (id: string): string => {
    if (!SESSION_ID.test(id)) throw new Error('playerthree/history: unsafe session id');
    return join(dir, `${id}.json`);
  };
  return {
    load() {
      mkdirSync(dir, { recursive: true });
      const records: SessionRecord[] = [];
      for (const name of readdirSync(dir)) {
        const json = name.indexOf('.json');
        if (name.endsWith('.tmp') && json > 0 && SESSION_ID.test(name.slice(0, json))) {
          // A write interrupted by a crash: never renamed into place.
          rmSync(join(dir, name), { force: true });
          continue;
        }
        if (!name.endsWith('.json') || !SESSION_ID.test(name.slice(0, -5))) continue;
        try {
          const data = JSON.parse(readFileSync(join(dir, name), 'utf8')) as { format?: unknown; version?: unknown; record?: SessionRecord; replay?: unknown };
          const r = data.record;
          if (data.format !== 'playerthree.session' || data.version !== 1 || !r || r.id !== name.slice(0, -5)) continue;
          const kept = r.replay === true && data.replay !== null && typeof data.replay === 'object';
          records.push({ ...r, replay: kept });
        } catch {
          console.error(`playerthree/history: skipping unreadable ${join(dir, name)}`);
        }
      }
      return records;
    },
    async save(record, replay) {
      const target = file(record.id);
      const tmp = `${target}.${process.pid}.tmp`;
      await writeFile(tmp, `{"format":"playerthree.session","version":1,"record":${JSON.stringify(record)},"replay":${replay ?? 'null'}}`);
      await rename(tmp, target);
    },
    async delete(id) {
      await rm(file(id), { force: true });
    },
    async loadReplay(id) {
      const data = JSON.parse(await readFile(file(id), 'utf8')) as { replay?: Replay | null };
      return data.replay ?? undefined;
    },
  };
}


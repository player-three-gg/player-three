/**
 * Generated TypeScript declarations of a game manifest (spec §11 *Generated types*) and the `expected` text of invalid
 * intent acks (spec §4), which speaks the same vocabulary: both name intent types through `intentTypeNames`, so an ack
 * can be read directly against the declarations served as the `types` topic.
 */
import { intentSchema, observationSections, type AnyManifest, type IntentDef } from './manifest.ts';
import { schemaBoundNote, schemaToTs, tsDocComment, tsUnion, type EnumS, type Fields, type Schema, type SchemaPath, type TsDocs } from './schema.ts';

/** Longest `expected` text of an invalid ack, in UTF-16 code units. */
export const EXPECTED_MAX = 512;

/**
 * Generated type name of every intent kind, in the given (manifest) order: the kind's alphanumeric runs PascalCased plus
 * `Intent` (`queue_add` → `QueueAddIntent`); a repeated name gets `_2`, `_3`, … Takes the kinds rather than a manifest
 * so tools that only know the agent-visible surface (the CLI audit) derive the very same names.
 */
export function intentTypeNames(kinds: readonly string[]): Map<string, string> {
  const names = new Map<string, string>();
  const used = new Set<string>();
  for (const kind of kinds) {
    // Kinds are enum literals (leading letter), so the base is a valid identifier; `_n` suffixes cannot collide
    // with another base because PascalCasing drops every underscore.
    const base = `${(kind.match(/[A-Za-z0-9]+/g) ?? []).map((run) => run[0]!.toUpperCase() + run.slice(1)).join('')}Intent`;
    let name = base;
    for (let n = 2; used.has(name); n++) name = `${base}_${n}`;
    used.add(name);
    names.set(kind, name);
  }
  return names;
}

const namesCache = new WeakMap<object, Map<string, string>>();

function typeNames(m: AnyManifest): Map<string, string> {
  let names = namesCache.get(m);
  if (!names) {
    names = intentTypeNames(Object.keys(m.intents));
    namesCache.set(m, names);
  }
  return names;
}

/** Role names are enum literals, which may contain `.`, `<` or `>`: those keys must be quoted. */
const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

const literals = (values: readonly string[], indent = ''): string => tsUnion(values.map((v) => JSON.stringify(v)), indent);

/**
 * TypeScript declarations of a manifest for policy authors and agents: a global script (no `import`/`export`), so one
 * `.d.ts` serves a `// @ts-check` classic script through `/// <reference path>` as well as ES/TS modules. With `role`,
 * `Intent` is that role's kinds; without it `RoleIntents` maps every role to its kinds. `Think`, `Init` and `log` only
 * exist for games with policy mode. `think`, `init` and `detail` themselves are deliberately not declared: an ambient
 * declaration would turn the policy's own definition into an uncontextualized overload. `docs: 'bounds'` drops every
 * prose comment and keeps only bound notes (trailing `//`): the declarations of a large game shrink to a fraction.
 */
export function manifestDts(manifest: AnyManifest, options: { readonly role?: string; readonly docs?: TsDocs } = {}): string {
  const m = manifest;
  const roles = (m.roles as EnumS).values;
  const role = options.role;
  const docs = options.docs ?? 'full';
  if (role !== undefined && !roles.includes(role)) throw new Error(`playerthree/dts: unknown role ${JSON.stringify(role)}`);
  const defs = m.intents as Record<string, IntentDef>;
  const variants = intentSchema(m).variants;
  const names = typeNames(m);
  const kindsOf = (r: string): string[] => Object.keys(defs).filter((k) => defs[k]!.roles.includes(r)).map((k) => names.get(k)!);
  const comment = (doc: string): string => (docs === 'full' ? tsDocComment(doc) : '');
  // A long union starts on its own line (one member per line): no space before it then.
  const after = (type: string): string => (type.startsWith('\n') ? type : ` ${type}`);
  const alias = (doc: string, name: string, type: string): string => `${comment(doc)}type ${name} =${after(type)};`;
  const ts = (s: Schema): string => schemaToTs(s, '', docs);

  const blocks = [
    `// ${m.id} ${m.version}${role === undefined ? '' : ` (role ${role})`}: TypeScript declarations generated by playerthree manifestDts${docs === 'bounds' ? ' (bound notes only, no prose docs)' : ''}. Do not edit.`,
    alias('Seat roles.', 'Role', literals(roles)),
    alias('Teams (sides).', 'Team', literals((m.teams as EnumS).values)),
    alias('Observation sections (`never` when the game declares no observation scope).', 'Section', literals(observationSections(m))),
    alias('Observation detail a policy declares as its global `detail`: every section, or a list of sections.', 'Detail', '"all" | readonly Section[]'),
    alias(`A seat's fogged observation (game_observe, a policy's think input). ${(m.observation as Exclude<Schema, { t: 'opt' }>).doc ?? ''}`, 'Observation', ts(m.observation)),
    m.matchData
      ? alias(`The seat's immutable match bootstrap (topic match-data, a policy's init input). ${m.matchData.doc ?? ''}`, 'MatchData', ts(m.matchData))
      : alias('This game declares no match bootstrap.', 'MatchData', 'null'),
    ...Object.keys(defs).map((kind) =>
      alias(`${defs[kind]!.doc} Roles: ${defs[kind]!.roles.join(', ')}.`, names.get(kind)!, ts({ t: 'union', tag: 'kind', variants: { [kind]: variants[kind] as Fields } })),
    ),
    alias('Every intent kind.', 'IntentKind', literals(Object.keys(defs))),
    role === undefined
      ? alias('Any intent of the game (RoleIntents: what each role may send).', 'Intent', tsUnion([...names.values()]))
      : alias(`The intents role ${role} may send.`, 'Intent', tsUnion(kindsOf(role))),
    ...(role === undefined
      ? [alias('The intents each role may send.', 'RoleIntents', `{\n${roles.map((r) => `  ${IDENTIFIER.test(r) ? r : JSON.stringify(r)}:${after(tsUnion(kindsOf(r), '  '))};`).join('\n')}\n}`)]
      : []),
    ...(m.control.policy
      ? [
          alias('A policy\'s global `think`: called at the policy rate with the current observation; returns intents to send.', 'Think', '(obs: Observation) => Intent[]'),
          alias('A policy\'s optional global `init`: called once per instance with the match bootstrap, before any think.', 'Init', '(matchData: MatchData | null) => void'),
          `${comment('Appends one line to the policy\'s own logs (policy_status, practice results).')}declare function log(...args: unknown[]): void;`,
        ]
      : []),
  ];
  return `${blocks.join('\n\n')}\n`;
}

/** A node's type as one-line union members (objects as field-name shapes), in the declarations' vocabulary. */
function members(s: Schema): string[] {
  switch (s.t) {
    case 'enum':
      return s.values.map((v) => JSON.stringify(v));
    case 'opt':
      return members(s.item);
    case 'list': {
      const item = members(s.item);
      return [`${item.length > 1 ? `(${item.join(' | ')})` : item[0]}[]`];
    }
    case 'obj':
      return [shape(s.fields)];
    case 'union':
      return Object.entries(s.variants as Record<string, Fields>).map(([name, fields]) => shape(fields, `${s.tag}: ${JSON.stringify(name)}`));
    default:
      return [schemaToTs(s)];
  }
}

/** An object type listing only its field names (`?` for optional ones); `head` (a union tag) comes first. */
function shape(fields: Fields, head?: string): string {
  const keys = [...(head === undefined ? [] : [head]), ...Object.entries(fields).map(([k, f]) => (f.t === 'opt' ? `${k}?` : k))];
  return keys.length === 0 ? 'Record<string, never>' : `{ ${keys.join('; ')} }`;
}

/** `ref: members (bounds)`, cut to EXPECTED_MAX after the last whole union member that fits and then `| …`. */
export function fitExpected(ref: string, parts: readonly string[], bounds: string): string {
  const full = `${ref}: ${parts.join(' | ')}${bounds ? ` (${bounds})` : ''}`;
  if (full.length <= EXPECTED_MAX) return full;
  const more = ' | …';
  let out = `${ref}: ${parts[0]}`;
  if (parts.length < 2 || out.length + more.length > EXPECTED_MAX) return `${full.slice(0, EXPECTED_MAX - 1)}…`;
  for (let i = 1; i < parts.length; i++) {
    const next = `${out} | ${parts[i]}`;
    if (next.length + more.length > EXPECTED_MAX) break;
    out = next;
  }
  return `${out}${more}`;
}

/**
 * What the schema wanted at `path` of an invalid intent, as `<type reference>: <type>` in the vocabulary of the
 * generated declarations (spec §4): `MoveIntent["x"]: number (integer 0..63)`. `path` is the ack's schema path; `kind`
 * is the intent's declared kind once its tag validated (without it only `Intent` / `IntentKind` can be named). An
 * unknown field (`?`) names its enclosing object as a field-name shape, a union tag the variants' tag values. Derived
 * from the manifest and path only — never from the rejected value — and at most EXPECTED_MAX code units.
 */
export function expectedAt(manifest: AnyManifest, path: SchemaPath, kind?: string): string {
  const names = typeNames(manifest);
  if (path[0] === 'kind' && path.length === 1) return fitExpected('IntentKind', Object.keys(manifest.intents).map((k) => JSON.stringify(k)), '');
  const name = kind === undefined ? undefined : names.get(kind);
  if (name === undefined || path.length === 0) return fitExpected('Intent', [...names.values()], '');
  const params = (manifest.intents as Record<string, IntentDef>)[kind!]!.params;
  // The intent object itself: `kind` is a field like the others for the shape of an unknown-field failure.
  return schemaExpected({ t: 'obj', fields: { kind: { t: 'enum', values: [kind!] }, ...params } }, name, path);
}

/**
 * What `root` (referred to as `ref`, e.g. `MatchOptions`) wanted at `path`, as `<ref>["field"][number]…: <type>`, in
 * the same vocabulary and bound as {@link expectedAt}; from the schema and path only, never the rejected value.
 */
export function schemaExpected(root: Schema, ref: string, path: SchemaPath): string {
  let nodes: Schema[] = [root];
  for (const seg of path) {
    if (seg === '?') break;
    const next: Schema[] = [];
    for (const raw of nodes) {
      const s = raw.t === 'opt' ? raw.item : raw;
      if (typeof seg === 'number') {
        if (s.t === 'list') next.push(s.item);
        else if (s.t === 'ints') next.push({ t: 'int', min: s.min, max: s.max });
      } else if (s.t === 'obj' && Object.hasOwn(s.fields, seg)) next.push(s.fields[seg]);
      else if (s.t === 'union') {
        // The path does not say which variant failed: every variant declaring the field is a candidate.
        if (seg === s.tag) next.push({ t: 'enum', values: Object.keys(s.variants) });
        else for (const fields of Object.values(s.variants as Record<string, Fields>)) if (Object.hasOwn(fields, seg)) next.push(fields[seg]!);
      }
    }
    if (next.length === 0) break;
    nodes = next;
    ref += typeof seg === 'number' ? '[number]' : `[${JSON.stringify(seg)}]`;
  }
  if (nodes.length === 1) return fitExpected(ref, members(nodes[0]!), schemaBoundNote(nodes[0]!));
  const parts = nodes.map((s) => {
    const bounds = schemaBoundNote(s);
    return `${members(s).join(' | ')}${bounds ? ` (${bounds})` : ''}`;
  });
  return fitExpected(ref, [...new Set(parts)], '');
}

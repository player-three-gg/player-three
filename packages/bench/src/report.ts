/** Writes a finished series' exports to a directory: results.json, results.zip, per-table CSVs, available replay artifacts and guardrails.json. */
import { createWriteStream } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { pipeline } from 'node:stream/promises';
import type { GameMatchHost, ResultsEnvelope, SeriesAccess, SeriesRunner } from 'playerthree/arena';
import type { Guardrail } from './bots-config.ts';
import { serializeResultsCsv, validateResultsEnvelope } from 'playerthree/results';
import { evaluateGuardrails } from './guardrails.ts';

/**
 * Export bytes are generated by the service, never by a second benchmark-specific serializer. The returned envelope is
 * the parsed canonical `results.json` download; the ZIP is pinned to the same revision.
 */
export async function writeResults(outDir: string, runner: SeriesRunner, access: SeriesAccess, host: GameMatchHost, guardrails: readonly Guardrail[]): Promise<ResultsEnvelope> {
  await mkdir(outDir, { recursive: true });
  const jsonPath = join(outDir, 'results.json');
  await pipeline(runner.export(access, 'json'), createWriteStream(jsonPath));
  const results = validateResultsEnvelope(JSON.parse(await readFile(jsonPath, 'utf8')));
  await pipeline(runner.export(access, 'csv', results.revision), createWriteStream(join(outDir, 'results.zip')));
  const replays = results.tables.artifacts.filter((artifact) => artifact.availability === 'available');
  await mkdir(join(outDir, 'csv'), { recursive: true });
  for (const [name, contents] of serializeResultsCsv(results)) await writeFile(join(outDir, 'csv', name), contents);
  if (replays.length) await mkdir(join(outDir, 'artifacts'), { recursive: true });
  for (const artifact of replays) {
    const parts: Uint8Array[] = [];
    for await (const part of await host.artifact(artifact.id)) parts.push(part);
    await writeFile(join(outDir, 'artifacts', `${encodeURIComponent(artifact.id)}.json`), Buffer.concat(parts));
  }
  if (guardrails.length) await writeFile(join(outDir, 'guardrails.json'), `${JSON.stringify(evaluateGuardrails(results, guardrails), null, 2)}\n`);
  return results;
}

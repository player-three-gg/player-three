/** TypeDoc's markdown output, generated by `scripts/api.ts` before every dev or build run. */
export const API_SOURCE_DIR = 'site/generated/api/';
export const API_ROUTE = '/api/';

/** `site/generated/api/playerthree/host.md` → `/api/playerthree/host/`; the index file is `/api/`. */
export function apiRoute(source: string): string {
  const path = source.slice(API_SOURCE_DIR.length).replace(/\.md$/, '');
  return path === 'index' ? API_ROUTE : `${API_ROUTE}${path}/`;
}

const BY_SOURCE = new Map<string, string>(DOC_PAGES.map((page) => [page.source, page.route]));

/** The site route that renders a repository file, if any. */
export function routeForSource(source: string): string | undefined {
  if (source.startsWith(API_SOURCE_DIR) && source.endsWith('.md')) return apiRoute(source);
  return BY_SOURCE.get(source);
}

/** Canonical form of a browser path: always a trailing slash, never `index.html`. */
export function normalizePath(pathname: string): string {
  const path = pathname.replace(/index\.html$/, '');
  return path.endsWith('/') ? path : `${path}/`;
}
